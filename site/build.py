#!/usr/bin/env python3
"""Build Isotope's website into a directory (default: _site).

    python3 site/build.py [--out DIR] [--offline] [--release-json FILE]

What it does:

- Writes the [night] roles of theme/palette.toml as CSS custom properties,
  so the page has the desktop's colours and cannot drift from them.
- Self-hosts the fonts the GUI tools use (pkg/guikit/fonts): Urbanist from the
  tree, Inter and JetBrains Mono as woff2 from the release zips the Dockerfile
  pins (same version and SHA-256). When that download fails, it uses the TTFs
  in pkg/guikit/fonts instead. The licences are copied next to them.
- Copies the GUI screenshot goldens it shows from cmd/*/testdata.
- Renders the user guide, site/guide/*.md, into guide/ (site/guide.py).
- Reads the latest GitHub release and its build manifests
  (scripts/release-manifest.sh) and renders one download button per ISO.
  Without the API (--offline, no network, rate limit), every button links to
  the release page instead, and the build still succeeds.

Only the Python standard library. GITHUB_TOKEN (or GH_TOKEN), when set, is sent
to the GitHub API. GITHUB_REPOSITORY overrides the repository.
"""

import argparse
import datetime
import hashlib
import html
import io
import json
import os
import re
import shutil
import sys
import tomllib
import urllib.error
import urllib.request
import zipfile

import guide

SITE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(SITE)
REPO = os.environ.get("GITHUB_REPOSITORY", "kairos-community/isotope")
REPO_URL = f"https://github.com/{REPO}"
LATEST_URL = f"{REPO_URL}/releases/latest"

# The download matrix: rows in the README's order.
DESKTOPS = [
    ("cosmic", "COSMIC"),
    ("niri", "niri"),
    ("sway", "Sway"),
    ("i3", "i3"),
]
LINES = [
    ("full", "PCs and laptops"),
    ("vm", "virtual machines"),
]
ISO_NAME = re.compile(
    r"^isotope-(?P<flavor>sway|i3|niri|cosmic|server)(?P<vm>-vm)?(?P<uki>-uki)?-(?P<tag>v[^/]+)-amd64\.iso$"
)
# The Trusted Boot edition (docs/TRUSTED_BOOT_KEYS.md): one ISO per desktop on
# the full line and one for the server, published when the release has them.
TRUSTED = DESKTOPS + [("server", "Server")]

# Screenshots the page shows: (source in the tree, published name).
SCREENSHOTS = [
    ("cmd/isotope-welcome/testdata/live-sway-1440x900.png", "img/live-welcome.png"),
    ("cmd/isotope-install-gui/testdata/5-encryption-1440x900.png", "img/installer-encryption.png"),
    ("cmd/isotope-welcome/testdata/apps-default-1440x900.png", "img/welcome-apps.png"),
]

# Fonts: (family, weight, woff2 path in the pinned zip, fallback TTF in the tree).
FONT_ZIPS = {
    "inter": ("INTER_VERSION", "INTER_SHA256",
              "https://github.com/rsms/inter/releases/download/v{v}/Inter-{v}.zip"),
    "jbm": ("JETBRAINS_MONO_VERSION", "JETBRAINS_MONO_SHA256",
            "https://github.com/JetBrains/JetBrainsMono/releases/download/v{v}/JetBrainsMono-{v}.zip"),
}
FONTS = [
    ("Inter", 400, "inter", "web/Inter-Regular.woff2", "Inter-Regular.ttf"),
    ("Inter", 600, "inter", "web/Inter-SemiBold.woff2", "Inter-SemiBold.ttf"),
    ("JetBrains Mono", 500, "jbm", "fonts/webfonts/JetBrainsMono-Medium.woff2", "JetBrainsMono-Medium.ttf"),
]
FONT_LICENCES = ["LICENSE-Inter.txt", "OFL-JetBrainsMono.txt", "OFL-Urbanist.txt"]


def log(msg):
    print(f"build-site: {msg}", file=sys.stderr)


def http_get(url, api=False, timeout=30):
    headers = {"User-Agent": "isotope-site-build"}
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if api:
        headers["Accept"] = "application/vnd.github+json"
        if token:
            headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.read()


# --- palette -------------------------------------------------------------

def palette_css():
    with open(os.path.join(ROOT, "theme/palette.toml"), "rb") as f:
        night = tomllib.load(f)["night"]
    lines = [f"  --{k.replace('_', '-')}: {v};" for k, v in night.items()]
    return ("/* Generated by site/build.py from theme/palette.toml [night]. */\n"
            ":root {\n" + "\n".join(lines) + "\n  color-scheme: dark;\n}\n")


# --- fonts ---------------------------------------------------------------

def dockerfile_arg(name):
    with open(os.path.join(ROOT, "Dockerfile")) as f:
        for line in f:
            m = re.match(rf"^ARG {name}=(\S+)", line)
            if m:
                return m.group(1)
    raise SystemExit(f"build-site: no ARG {name} in the Dockerfile")


def font_zip(key, offline):
    if offline:
        return None
    vname, sname, url = FONT_ZIPS[key]
    version, want = dockerfile_arg(vname), dockerfile_arg(sname)
    cache = os.path.join(os.environ.get("XDG_CACHE_HOME", os.path.expanduser("~/.cache")),
                         "isotope-site", f"{key}-{version}.zip")
    data = None
    if os.path.exists(cache):
        with open(cache, "rb") as f:
            data = f.read()
    if data is None or hashlib.sha256(data).hexdigest() != want:
        try:
            data = http_get(url.format(v=version), timeout=120)
        except (urllib.error.URLError, OSError) as e:
            log(f"could not download {key} {version} ({e}); using the TTF fallback")
            return None
        if hashlib.sha256(data).hexdigest() != want:
            log(f"{key} {version}: checksum mismatch; using the TTF fallback")
            return None
        try:
            os.makedirs(os.path.dirname(cache), exist_ok=True)
            with open(cache, "wb") as f:
                f.write(data)
        except OSError:
            pass
    return zipfile.ZipFile(io.BytesIO(data))


def build_fonts(out, offline):
    os.makedirs(os.path.join(out, "fonts"), exist_ok=True)
    guikit = os.path.join(ROOT, "pkg/guikit/fonts")
    zips = {k: font_zip(k, offline) for k in FONT_ZIPS}
    faces = []

    shutil.copy(os.path.join(guikit, "Urbanist-SemiBold.ttf"), os.path.join(out, "fonts"))
    faces.append(("Urbanist", 600, "fonts/Urbanist-SemiBold.ttf", "truetype"))

    for family, weight, key, member, ttf in FONTS:
        z = zips[key]
        if z is not None and member in z.namelist():
            name = os.path.basename(member)
            with open(os.path.join(out, "fonts", name), "wb") as f:
                f.write(z.read(member))
            faces.append((family, weight, f"fonts/{name}", "woff2"))
        else:
            shutil.copy(os.path.join(guikit, ttf), os.path.join(out, "fonts"))
            faces.append((family, weight, f"fonts/{ttf}", "truetype"))

    for lic in FONT_LICENCES:
        shutil.copy(os.path.join(guikit, lic), os.path.join(out, "fonts"))

    css = "/* Self-hosted, SIL Open Font Licence; see fonts/. */\n"
    for family, weight, path, fmt in faces:
        css += ("@font-face {\n"
                f"  font-family: \"{family}\";\n  font-style: normal;\n  font-weight: {weight};\n"
                f"  font-display: swap;\n  src: url(\"{path}\") format(\"{fmt}\");\n}}\n")
    preload = [p for fam, w, p, _ in faces if (fam, w) in (("Urbanist", 600), ("Inter", 400))]
    return css, preload


# --- the release ---------------------------------------------------------

def fetch_release(offline, release_json):
    """The latest release as the API returns it, or None."""
    if release_json:
        with open(release_json) as f:
            return json.load(f)
    if offline:
        return None
    try:
        return json.loads(http_get(f"https://api.github.com/repos/{REPO}/releases/latest", api=True))
    except (urllib.error.URLError, OSError, ValueError) as e:
        log(f"could not read the latest release ({e}); buttons link to the release page")
        return None


def release_isos(release, offline):
    """{(flavor, line): iso} for the ISOs the page offers."""
    if not release:
        return {}
    tag = release.get("tag_name", "")
    assets = {a["name"]: a for a in release.get("assets", [])}
    isos = {}

    def add(flavor, gpu, name, sha):
        asset = assets.get(name)
        if not asset or (flavor == "server" and gpu not in ("full", "uki")):
            return
        sums = assets.get(name + ".sha256")
        isos[(flavor, gpu)] = {
            "name": name,
            "url": asset["browser_download_url"],
            "size": asset.get("size", 0),
            "sha256": sha or "",
            "sha256_url": sums["browser_download_url"] if sums else "",
        }

    for name, asset in assets.items():
        if not name.endswith(".iso.build.json"):
            continue
        m = None
        if not offline:
            try:
                m = json.loads(http_get(asset["browser_download_url"]))
            except (urllib.error.URLError, OSError, ValueError) as e:
                log(f"could not read {name} ({e}); parsing the asset names")
        if not m:
            continue
        if m.get("desktop_flavor") not in {"sway", "i3", "niri", "cosmic", "server"}:
            continue
        if m.get("release_tag") != tag:
            continue
        line = "uki" if m.get("trusted_boot") else m.get("gpu")
        add(m["desktop_flavor"], line, m.get("iso", ""), m.get("iso_sha256", ""))

    # Any ISO the manifests did not cover: its name says what it is.
    for name in assets:
        n = ISO_NAME.match(name)
        if not n or n.group("tag") != tag:
            continue
        if n.group("vm") and n.group("uki"):
            continue
        key = (n.group("flavor"), "uki" if n.group("uki") else "vm" if n.group("vm") else "full")
        if key not in isos:
            add(key[0], key[1], name, "")
    return isos


def human_size(n):
    if n >= 1e9:
        return f"{n / 1e9:.1f} GB"
    return f"{round(n / 1e6)} MB"


def release_date(release):
    try:
        d = datetime.datetime.fromisoformat(release["published_at"].replace("Z", "+00:00"))
        return f"{d.day} {d:%B %Y}"
    except (KeyError, TypeError, ValueError):
        return ""


# --- rendering -----------------------------------------------------------

e = html.escape


def download_item(flavor, line, label, iso):
    """One download: a button, and beside it the checksum."""
    if not iso:
        return (f'<div class="dl" data-flavor="{flavor}" data-line="{line}">'
                f'<a class="dl-button dl-button--fallback" href="{LATEST_URL}">'
                f'<span class="dl-what">{e(label)}</span>'
                f'<span class="dl-file">Get it from the release page</span></a></div>')
    sha = iso["sha256"]
    sum_html = ""
    if iso["sha256_url"]:
        short = f' <code class="dl-hash" title="{e(sha)}">{e(sha[:12])}…</code>' if sha else ""
        sum_html = (f'<p class="dl-sum"><a href="{e(iso["sha256_url"])}">SHA-256 checksum</a>'
                    f'{short}</p>')
    return (f'<div class="dl" data-flavor="{flavor}" data-line="{line}">'
            f'<a class="dl-button" href="{e(iso["url"])}" data-size="{e(human_size(iso["size"]))}">'
            f'<span class="dl-what">{e(label)}</span>'
            f'<span class="dl-file">{e(iso["name"])}</span>'
            f'<span class="dl-size">{e(human_size(iso["size"]))}</span></a>'
            f'{sum_html}</div>')


def render_downloads(isos):
    rows = []
    for flavor, title in DESKTOPS:
        cells = "".join(
            download_item(flavor, line, f"Isotope {title} for {what}", isos.get((flavor, line)))
            for line, what in LINES)
        rows.append(f'<div class="dl-row"><h3 class="dl-row-title" id="dl-{flavor}">{e(title)}</h3>'
                    f'<div class="dl-cells">{cells}</div></div>')
    server = download_item("server", "full", "Isotope Server", isos.get(("server", "full")))
    rows.append('<div class="dl-row dl-row--server"><h3 class="dl-row-title" id="dl-server">Server</h3>'
                f'<div class="dl-cells">{server}'
                '<p class="dl-note">No desktop. One ISO for real machines and VMs.</p></div></div>')
    return "\n".join(rows)


def render_trusted(isos):
    """The Trusted Boot downloads, or nothing when the release has none."""
    items = [(flavor, title, isos.get((flavor, "uki"))) for flavor, title in TRUSTED]
    if not any(iso for _, _, iso in items):
        return ""
    cells = "".join(
        download_item(flavor, "uki", f"Isotope {title}, Trusted Boot" if flavor != "server"
                      else "Isotope Server, Trusted Boot", iso)
        for flavor, title, iso in items if iso)
    return (
        '<div class="trusted" id="trusted-boot">'
        '<h3 class="trusted-title">Trusted Boot edition</h3>'
        '<p class="trusted-lede">For PCs with UEFI Secure Boot and a TPM 2.0 chip. The computer '
        'starts only Isotope images signed by the project, and the disk is encrypted with a key '
        'kept in the TPM, so it cannot be read in another computer.</p>'
        '<ul class="trusted-notes">'
        '<li>Start the ISO with Secure Boot in setup mode. On the first boot it enrolls the '
        "project's keys and restarts. Most laptops need the keys cleared in the firmware setup "
        'first.</li>'
        '<li>Secure Boot must stay on afterwards. It needs 4 GB of RAM, 8 GB for COSMIC.</li>'
        '<li>Upgrades stay in the Trusted Boot edition. To leave it, reinstall from a normal ISO.</li>'
        '</ul>'
        f'<div class="dl-cells trusted-cells">{cells}</div>'
        '</div>')


def render(release, isos, fonts_preload):
    with open(os.path.join(SITE, "index.html")) as f:
        page = f.read()
    if release and isos:
        tag = release["tag_name"]
        date = release_date(release)
        when = f", released {date}" if date else ""
        version = (f'<a href="{e(release["html_url"])}">Isotope {e(tag)}</a>{e(when)}. '
                   "For 64-bit PCs (amd64).")
        state = "release"
    else:
        version = (f'The ISOs are on the <a href="{LATEST_URL}">latest release page</a>. '
                   "For 64-bit PCs (amd64).")
        state = "fallback"
    preload = "\n".join(
        f'<link rel="preload" href="{p}" as="font" type="font/{"woff2" if p.endswith("woff2") else "ttf"}" crossorigin>'
        for p in fonts_preload)
    values = {
        "repo_url": REPO_URL,
        "latest_url": LATEST_URL,
        "version_line": version,
        "downloads": render_downloads(isos),
        "trusted": render_trusted(isos),
        "downloads_state": state,
        "font_preload": preload,
        "year": str(datetime.date.today().year),
    }
    for k, v in values.items():
        page = page.replace("{{" + k + "}}", v)
    left = re.findall(r"\{\{[a-z_]+\}\}", page)
    if left:
        raise SystemExit(f"build-site: unfilled placeholders in index.html: {left}")
    return page


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(ROOT, "_site"))
    ap.add_argument("--offline", action="store_true", help="no network: TTF fonts, release-page links")
    ap.add_argument("--release-json", help="use this release JSON (the API's format) instead of the API")
    args = ap.parse_args()

    out = os.path.abspath(args.out)
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(os.path.join(out, "img"))

    for name in ("app.js", "favicon.svg"):
        shutil.copy(os.path.join(SITE, name), out)
    for name in os.listdir(os.path.join(SITE, "img")):
        shutil.copy(os.path.join(SITE, "img", name), os.path.join(out, "img"))
    for src, dst in SCREENSHOTS:
        shutil.copy(os.path.join(ROOT, src), os.path.join(out, dst))
    shutil.copy(os.path.join(ROOT, "LICENSE"), os.path.join(out, "LICENSE.txt"))

    fonts_css, preload = build_fonts(out, args.offline)
    with open(os.path.join(SITE, "style.css")) as f:
        style = f.read()
    with open(os.path.join(out, "site.css"), "w") as f:
        f.write(palette_css() + fonts_css + style)

    release = fetch_release(args.offline, args.release_json)
    isos = release_isos(release, args.offline or bool(args.release_json))
    with open(os.path.join(out, "index.html"), "w") as f:
        f.write(render(release, isos, preload))
    try:
        pages = guide.build(out, REPO_URL)
    except guide.GuideError as err:
        raise SystemExit(f"build-site: user guide: {err}")
    log(f"user guide: {len(pages)} page(s)")
    # GitHub Pages: serve the files as they are.
    open(os.path.join(out, ".nojekyll"), "w").close()

    tag = release.get("tag_name") if release else None
    log(f"wrote {out}: release {tag or 'none (release page links)'}, {len(isos)} ISO button(s)")


if __name__ == "__main__":
    main()
